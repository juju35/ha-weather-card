function wxT(lang, key, vars) {
  const s = (WX_I18N[lang] || WX_I18N.en)[key] ?? WX_I18N.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "") : s;
}

function wxLang(config, hass) {
  const raw = String(config?.language || hass?.language || globalThis.document?.documentElement?.lang || "en");
  if (Object.hasOwn(WX_I18N, raw)) return raw;
  const base = raw.split("-")[0];
  return Object.hasOwn(WX_I18N, base) ? base : "en";
}

// The locale handed to Intl / toLocale*: the full Home Assistant locale (or the card's `language:`, which comes first)
// when it is in the card's language, else that language. "pt" alone is European Portuguese, which Intl reads as Brazilian.
function wxIntlLang(config, hass) {
  const lang = wxLang(config, hass);
  let loc = String(config?.language || hass?.locale?.language || hass?.language || "");
  if (loc.split("-")[0].toLowerCase() !== lang.split("-")[0]) loc = lang;
  if (lang === "sr-Latn" && !/-latn\b/i.test(loc)) loc = "sr-Latn";
  if (loc.toLowerCase() === "pt") loc = "pt-PT";
  try {
    Intl.getCanonicalLocales(loc);
  } catch {
    loc = lang === "pt" ? "pt-PT" : lang;
  }
  return loc;
}

function wxEsc(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

const wxUnavailable = (st) => !st || st.state === "unavailable" || st.state === "unknown";
const wxNumber = (v) => (v == null || v === "" ? null : Number.isFinite(Number(v)) ? Number(v) : null);
const wxNum = (st) => (wxUnavailable(st) ? null : wxNumber(st.state));
const wxClamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

// Lower case, accents dropped, separators as "_": the form entity ids, states and attribute names are matched in.
const wxNorm = (v) =>
  String(v ?? "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[\s_-]+/g, "_");

function wxFmtNum(lang, v, digits = 1) {
  if (v == null || !Number.isFinite(v)) return "—";
  return v.toLocaleString(lang, { maximumFractionDigits: digits, useGrouping: false });
}

// Pressures and precipitation in the units the card's scales are written in (hPa, mm), from the unit their source
